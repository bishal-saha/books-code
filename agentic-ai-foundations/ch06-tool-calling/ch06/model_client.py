"""Chapter 3's provider-neutral model client, extended for tool calling.

New in Chapter 6: ToolDefinition, ToolCall, ToolResult and ToolChoice; a Message that can carry
tool calls or tool results; complete() takes tools and a tool choice. Every new field and
parameter has a default, so a Chapter 3 call (system, messages, max_tokens) still works.
"""

from collections.abc import Sequence
from typing import Any, Literal, Protocol

from pydantic import BaseModel, Field

StopReason = Literal["finished", "truncated", "tool_call", "other"]
ErrorKind = Literal["timeout", "rate_limited", "auth", "bad_request", "provider_error"]


class ToolDefinition(BaseModel):
    name: str
    description: str
    input_schema: dict[str, Any]  # JSON Schema; the top level is an object


class ToolCall(BaseModel):
    id: str  # generated by the provider; the result must carry it back
    name: str
    arguments: dict[str, Any]


class ToolResult(BaseModel):
    tool_call_id: str  # the id of the ToolCall this result answers
    content: str
    is_error: bool = False


class ToolChoice(BaseModel):
    mode: Literal["auto", "required", "none", "tool"] = "auto"
    tool_name: str | None = None  # only for mode="tool"
    allow_parallel: bool = True  # False: at most one tool call per response


class Message(BaseModel):
    role: Literal["user", "assistant"]
    content: str = ""
    tool_calls: list[ToolCall] = Field(default_factory=list)  # assistant messages only
    tool_results: list[ToolResult] = Field(default_factory=list)  # user messages only


class Usage(BaseModel):
    input_tokens: int  # all input, cached tokens included
    output_tokens: int


class ModelResponse(BaseModel):
    text: str  # may be empty when the model only asks for tools
    stop_reason: StopReason
    usage: Usage
    tool_calls: list[ToolCall] = Field(default_factory=list)
    request_id: str | None = None


class ModelError(Exception):
    def __init__(self, kind: ErrorKind, message: str, request_id: str | None = None) -> None:
        super().__init__(message)
        self.kind = kind
        self.request_id = request_id


class ModelClient(Protocol):
    def complete(
        self,
        system: str,
        messages: Sequence[Message],
        max_tokens: int,
        tools: Sequence[ToolDefinition] = (),
        tool_choice: ToolChoice | None = None,
    ) -> ModelResponse: ...


def assistant_message(response: ModelResponse) -> Message:
    """The model's turn, rebuilt for the history: its text and its tool calls."""
    return Message(role="assistant", content=response.text, tool_calls=response.tool_calls)


def tool_results_message(results: Sequence[ToolResult]) -> Message:
    """Every result for one model response goes back together, in ONE user message."""
    return Message(role="user", tool_results=list(results))
